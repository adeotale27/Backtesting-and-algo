def validate_positions_vs_zerodha(kite_client, target_date: date) -> dict:
    """Compare trade journal implied open positions against Zerodha actual positions.

    Runs after EOD reconcile to detect mismatches: positions Zerodha shows that
    have no open leg in the journal (data gaps), and orphan open legs in the
    journal that Zerodha shows as flat (phantom orders).

    Args:
        kite_client: An authenticated KiteConnect instance.
        target_date: The date being validated (used for report filename).

    Returns:
        dict with keys:
            validated_at (str): ISO timestamp of validation run.
            matched (list): Symbols where journal and Zerodha agree.
            discrepancies (list): Symbols where Zerodha shows a position the
                journal lacks an open leg for. Each entry has:
                symbol, zerodha_qty, journal_qty, zerodha_avg_price,
                suggested_transaction_type, suggested_trade_date.
            phantoms (list): Symbols with a journal open leg but Zerodha qty=0.
                Each entry has: symbol, journal_qty, transaction_type.
    """
    validated_at = get_ist_now().isoformat()
    matched: list = []
    discrepancies: list = []
    phantoms: list = []

    # Fetch Zerodha net positions
    try:
        positions_data = kite_client.positions()
        net_positions = positions_data.get("net", [])
    except Exception as exc:
        logging.error("validate_positions_vs_zerodha: kite.positions() failed: %s", exc)
        return {
            "validated_at": validated_at,
            "error": str(exc),
            "matched": [],
            "discrepancies": [],
            "phantoms": [],
        }

    # Build Zerodha position map: symbol → {qty, avg_price}
    zerodha_map: dict[str, dict] = {}
    for pos in net_positions:
        sym = pos.get("tradingsymbol", "")
        qty = int(pos.get("quantity", 0))
        avg_price = float(pos.get("average_price", 0))
        if sym and qty != 0:
            zerodha_map[sym] = {"qty": qty, "avg_price": avg_price}

    # Build journal implied open positions from unpaired orders across all dates
    import trade_journal_db as tjdb
    tjdb.ensure_cache_fresh()
    unpaired_rows = tjdb.query_unpaired_all()  # returns list of unpaired order dicts

    # Aggregate unpaired by symbol: positive = net long (more buys), negative = net short
    journal_map: dict[str, dict] = {}
    for order in unpaired_rows:
        sym = order.get("symbol", "")
        qty = int(order.get("quantity", 0))
        txn = order.get("transaction_type", "")
        if not sym:
            continue
        if sym not in journal_map:
            journal_map[sym] = {"qty": 0, "orders": []}
        delta = qty if txn == "BUY" else -qty
        journal_map[sym]["qty"] += delta
        journal_map[sym]["orders"].append(order)

    # Compare Zerodha positions against journal
    all_symbols = set(zerodha_map) | set(journal_map)
    for sym in all_symbols:
        z_qty = zerodha_map.get(sym, {}).get("qty", 0)
        j_qty = journal_map.get(sym, {}).get("qty", 0)
        z_avg = zerodha_map.get(sym, {}).get("avg_price", 0.0)

        if z_qty == j_qty:
            if z_qty != 0:
                matched.append({"symbol": sym, "qty": z_qty})
        elif z_qty != 0 and j_qty == 0:
            # Zerodha has position; journal has no open leg → data gap
            # Suggest carry-forward: inject the OPPOSITE of the current position
            # (Zerodha -325 means a short was opened — inject a SELL)
            suggested_txn = "SELL" if z_qty < 0 else "BUY"
            discrepancies.append({
                "symbol": sym,
                "zerodha_qty": z_qty,
                "journal_qty": j_qty,
                "zerodha_avg_price": z_avg,
                "suggested_transaction_type": suggested_txn,
                "suggested_quantity": abs(z_qty),
                "suggested_trade_date": (target_date - timedelta(days=1)).isoformat(),
            })
        elif z_qty == 0 and j_qty != 0:
            # Journal has open leg; Zerodha is flat → phantom order in journal
            txn_type = "BUY" if j_qty > 0 else "SELL"
            phantoms.append({
                "symbol": sym,
                "journal_qty": j_qty,
                "transaction_type": txn_type,
                "orders": journal_map[sym]["orders"],
            })
        else:
            # Both non-zero but differ in magnitude
            suggested_txn = "SELL" if z_qty < 0 else "BUY"
            discrepancies.append({
                "symbol": sym,
                "zerodha_qty": z_qty,
                "journal_qty": j_qty,
                "zerodha_avg_price": z_avg,
                "suggested_transaction_type": suggested_txn,
                "suggested_quantity": abs(z_qty - j_qty),
                "suggested_trade_date": (target_date - timedelta(days=1)).isoformat(),
            })

    report = {
        "validated_at": validated_at,
        "matched": matched,
        "discrepancies": discrepancies,
        "phantoms": phantoms,
    }

    # Persist report so the API can serve it without re-running
    try:
        status_dir = _get_status_dir()
        report_path = os.path.join(
            status_dir, f"position_validation_{target_date.isoformat()}.json"
        )
        with open(report_path, "w") as f:
            json.dump(report, f, indent=2)
        logging.info("validate_positions_vs_zerodha: report saved to %s", report_path)
    except Exception as exc:
        logging.error("validate_positions_vs_zerodha: failed to save report: %s", exc)

    logging.info(
        "validate_positions_vs_zerodha: date=%s matched=%d discrepancies=%d phantoms=%d",
        target_date, len(matched), len(discrepancies), len(phantoms),
    )
    return report


