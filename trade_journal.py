# Zerodha Reconciliation (for manual trades placed outside the system)
# ============================================================================

def reconcile_with_zerodha(kite_client, target_date: date) -> dict:
    """Fetch kite.trades() and insert any fills missing from the local JSON.

    Zerodha's trade API only covers the current session, so this function is
    only effective for today's date. Trades already present are identified by
    ``order_id`` (exact) or by ``symbol + transaction_type + quantity`` (fallback
    for records written before the order_id field was added).

    Partial fills from CANCELLED or REJECTED orders are skipped — they are not
    complete executions and would leave unmatched legs in the journal.

    Missing trades are saved with ``algo_source="Manual"`` since they were placed
    directly on Zerodha outside the trading system.

    Args:
        kite_client: An authenticated KiteConnect instance.
        target_date: The date to reconcile (should be today).

    Returns:
        dict with keys:
            added (int): Number of trades added.
            skipped (int): Number of trades already present.
            partial_skipped (int): Partial fills from cancelled/rejected orders skipped.
            errors (list[str]): Descriptions of any per-trade errors.
    """
    added = 0
    skipped = 0
    partial_skipped = 0
    errors: list = []

    try:
        zerodha_trades = kite_client.trades()
    except Exception as exc:
        logging.error("reconcile_with_zerodha: kite.trades() failed: %s", exc)
        return {"added": 0, "skipped": 0, "partial_skipped": 0, "errors": [str(exc)]}

    # Fetch order metadata to detect partial fills from cancelled/rejected orders.
    # A fill from kite.trades() may be a partial fill if its parent order was
    # subsequently cancelled — these create phantom open legs in the journal.
    try:
        zerodha_orders = kite_client.orders()
        order_status_map: dict[str, dict] = {
            str(o.get("order_id", "")): o for o in zerodha_orders
        }
    except Exception as exc:
        logging.warning(
            "reconcile_with_zerodha: kite.orders() failed, partial-fill filtering disabled: %s",
            exc,
        )
        order_status_map = {}

    existing_orders = load_orders_for_date(target_date)

    # Build two lookup sets for dedup: by order_id and by (symbol, type, qty)
    existing_order_ids: set[str] = {
        str(o["order_id"]) for o in existing_orders if o.get("order_id")
    }
    existing_fuzzy_keys: set = {
        (o["symbol"], o["transaction_type"], int(o.get("quantity", 0)))
        for o in existing_orders
    }

    for trade in zerodha_trades:
        trade_order_id = str(trade.get("order_id", ""))
        symbol = trade.get("tradingsymbol", "")
        transaction_type = trade.get("transaction_type", "")
        quantity = int(trade.get("quantity", 0) or trade.get("filled_quantity", 0))
        fill_price = float(trade.get("average_price", 0) or trade.get("price", 0))

        if not symbol or not transaction_type or quantity <= 0:
            continue

        # Only journal F&O trades (NFO = NSE F&O, BFO = BSE F&O).
        # Equity/ETF trades on NSE/BSE are out of scope for the trade journal.
        trade_exchange = trade.get("exchange", "")
        if trade_exchange not in ("NFO", "BFO"):
            logging.debug(
                "reconcile_with_zerodha: skipping non-FNO trade %s on exchange=%s",
                symbol, trade_exchange,
            )
            continue

        # Skip partial fills from cancelled or rejected orders.
        # kite.trades() returns fill events even when the parent order was later
        # cancelled after partial execution — the unfilled remainder means the
        # position is not what it appears, leaving a phantom open leg in the journal.
        if trade_order_id and order_status_map:
            order_info = order_status_map.get(trade_order_id, {})
            order_final_status = order_info.get("status", "")
            if order_final_status in ("CANCELLED", "REJECTED"):
                order_total_qty = int(order_info.get("quantity", 0))
                order_filled_qty = int(order_info.get("filled_quantity", 0))
                if order_total_qty > 0 and order_filled_qty < order_total_qty:
                    logging.info(
                        "reconcile_with_zerodha: skipping partial fill "
                        "order_id=%s %s %s x%s (status=%s filled=%s/%s)",
                        trade_order_id, symbol, transaction_type, quantity,
                        order_final_status, order_filled_qty, order_total_qty,
                    )
                    partial_skipped += 1
                    continue

        # Exact dedup by order_id (preferred; covers all modern Zerodha trades)
        if trade_order_id and trade_order_id in existing_order_ids:
            skipped += 1
            continue

        # Fuzzy dedup: backward-compat ONLY for trades with no order_id.
        # Two different orders can legitimately share the same (symbol, type, qty)
        # on the same day, so we must never apply this check when order_id is present.
        if not trade_order_id:
            fuzzy_key = (symbol, transaction_type, quantity)
            if fuzzy_key in existing_fuzzy_keys:
                skipped += 1
                continue

        # Determine fill timestamp; fall back to IST now
        fill_ts = trade.get("fill_timestamp") or trade.get("order_timestamp")
        if fill_ts and not isinstance(fill_ts, str):
            fill_ts = fill_ts.isoformat()
        if not fill_ts:
            from common_lib import get_ist_now
            fill_ts = get_ist_now().isoformat()

        try:
            from common_lib import save_executed_order
            saved = save_executed_order(
                symbol=symbol,
                transaction_type=transaction_type,
                price=fill_price,
                quantity=quantity,
                algo_source="Manual",
                order_id=trade_order_id,
            )
            if saved:
                added += 1
                existing_order_ids.add(trade_order_id)
                # Do NOT update existing_fuzzy_keys here — order_id is the
                # dedup gate for modern trades.  Updating the fuzzy set would
                # incorrectly block a second legitimate order of the same
                # symbol/side/qty (but different order_id) later in this loop.
                logging.info(
                    "reconcile_with_zerodha: added missing trade %s %s %s x%s",
                    trade_order_id, symbol, transaction_type, quantity,
                )
            else:
                errors.append(f"save failed for order_id={trade_order_id} {symbol}")
        except Exception as exc:
            error_msg = f"error saving order_id={trade_order_id} {symbol}: {exc}"
            logging.error("reconcile_with_zerodha: %s", error_msg)
            errors.append(error_msg)

    logging.info(
        "reconcile_with_zerodha: date=%s added=%d skipped=%d partial_skipped=%d errors=%d",
        target_date, added, skipped, partial_skipped, len(errors),
    )
    return {"added": added, "skipped": skipped, "partial_skipped": partial_skipped, "errors": errors}


