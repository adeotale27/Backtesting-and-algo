def _get_status_dir() -> str:
    """Get the path to the status directory containing executed order files.

    Returns:
        str: Absolute path to the status directory.
    """
    base_dir = os.path.dirname(os.path.abspath(__file__))
    return os.path.join(os.path.dirname(base_dir), "status")


def load_orders_for_date(target_date: date) -> list:
    """Load executed orders for a specific date.

    Args:
        target_date: The date to load orders for.

    Returns:
        list: List of order dicts, empty if no file found.
    """
    status_dir = _get_status_dir()
    date_str = target_date.strftime("%Y-%m-%d")
    filepath = os.path.join(status_dir, f"executed_orders_{date_str}.json")

    if not os.path.exists(filepath):
        return []

    try:
        with open(filepath, "r") as f:
            data = json.load(f)
        orders = data.get("orders", [])
        # Add the date to each order for multi-day grouping
        for order in orders:
            order["trade_date"] = date_str
        return orders
    except Exception as e:
        logging.error(f"Error loading orders for {date_str}: {e}")
        return []


def load_orders_range(start_date: date, end_date: date) -> list:
    """Load executed orders across a date range.

    Args:
        start_date: Start date (inclusive).
        end_date: End date (inclusive).

    Returns:
        list: Combined list of orders from all dates, sorted by timestamp.
    """
    all_orders: list = []
    current = start_date

    while current <= end_date:
        orders = load_orders_for_date(current)
        all_orders.extend(orders)
        current += timedelta(days=1)

    # Sort by timestamp ascending for FIFO pairing
    all_orders.sort(key=lambda x: x.get("timestamp", ""))
    return all_orders


def get_available_dates() -> list:
    """Get all dates that have executed order files.

    Returns:
        list: Sorted list of date strings (YYYY-MM-DD).
    """
    status_dir = _get_status_dir()
    pattern = os.path.join(status_dir, "executed_orders_*.json")
    files = glob.glob(pattern)

    dates: list = []
    for f in files:
        basename = os.path.basename(f)
        # Extract date from "executed_orders_YYYY-MM-DD.json"
        date_str = basename.replace("executed_orders_", "").replace(".json", "")
        dates.append(date_str)

    dates.sort()
    return dates


# ============================================================================
# Trade Pairing (FIFO)
# ============================================================================

def pair_trades(orders: list) -> tuple:
    """Pair sell/buy orders into round trips using FIFO matching.

    For each symbol, matches the first sell with the first buy (sell-first)
    or first buy with the first sell (buy-first). Each pair becomes a
    "round trip" with P&L calculated.

    Args:
        orders: List of order dicts sorted by timestamp ascending.

    Returns:
        tuple: (round_trips list, unpaired orders list).
    """
    # Group orders by symbol
    symbol_orders: dict = {}
    for order in orders:
        sym = order.get("symbol", "")
        if sym not in symbol_orders:
            symbol_orders[sym] = {"sells": [], "buys": []}

        if order.get("transaction_type") == "SELL":
            symbol_orders[sym]["sells"].append(order)
        elif order.get("transaction_type") == "BUY":
            symbol_orders[sym]["buys"].append(order)

    round_trips: list = []
    unpaired: list = []

    for sym, data in symbol_orders.items():
        sells = list(data["sells"])  # Copy to avoid mutation
        buys = list(data["buys"])

        # FIFO matching: pair sell with buy in order
        while sells and buys:
            sell = sells[0]
            buy = buys[0]

            sell_time = sell.get("timestamp", "")
            buy_time = buy.get("timestamp", "")

            sell_qty = int(sell.get("quantity", 0))
            buy_qty = int(buy.get("quantity", 0))

            # Determine direction based on which came first
            if sell_time <= buy_time:
                # Sell-first (primary scenario for option selling)
                direction = "sell_first"
                open_trade = sell
                close_trade = buy
            else:
                # Buy-first (rare)
                direction = "buy_first"
                open_trade = buy
                close_trade = sell

            # Match on the minimum quantity
            matched_qty = min(sell_qty, buy_qty)
            sell_price = float(sell.get("price", 0))
            buy_price = float(buy.get("price", 0))

            # P&L: always (sell_price - buy_price) * matched_qty
            pnl = round((sell_price - buy_price) * matched_qty, 2)

            round_trips.append({
                "symbol": sym,
                "direction": direction,
                "open_trade": {
                    "timestamp": open_trade.get("timestamp"),
                    "transaction_type": open_trade.get("transaction_type"),
                    "price": float(open_trade.get("price", 0)),
                    "quantity": matched_qty,
                    "algo_source": open_trade.get("algo_source", "Unknown"),
                    "trade_date": open_trade.get(
                        "trade_date",
                        open_trade.get("timestamp", "")[:10],
                    ),
                    "order_id": open_trade.get("order_id", "") or "",
                },
                "close_trade": {
                    "timestamp": close_trade.get("timestamp"),
                    "transaction_type": close_trade.get("transaction_type"),
                    "price": float(close_trade.get("price", 0)),
                    "quantity": matched_qty,
                    "algo_source": close_trade.get("algo_source", "Unknown"),
                    "trade_date": close_trade.get(
                        "trade_date",
                        close_trade.get("timestamp", "")[:10],
                    ),
                    "order_id": close_trade.get("order_id", "") or "",
                },
                "matched_qty": matched_qty,
                "pnl": pnl,
                "option_type": open_trade.get("option_type", ""),
                "expiry": open_trade.get("expiry", ""),
            })

            # Reduce quantities
            if sell_qty > matched_qty:
                sells[0] = dict(sell)
                sells[0]["quantity"] = sell_qty - matched_qty
            else:
                sells.pop(0)

            if buy_qty > matched_qty:
                buys[0] = dict(buy)
                buys[0]["quantity"] = buy_qty - matched_qty
            else:
                buys.pop(0)

        # Remaining unmatched orders
        for s in sells:
            unpaired.append(s)
        for b in buys:
            unpaired.append(b)

    return round_trips, unpaired


# ============================================================================
# P&L Attribution
# ============================================================================

def attribute_pnl(round_trip: dict) -> dict:
    """Apply P&L attribution rules to a round trip.

    Sell-First Rules:
        - Algo sell → 100% to opening algo (regardless of close)
        - Manual sell + Algo close → 100% to closing algo
        - Manual sell + Manual close → 100% Manual

    Buy-First Rules:
        - Algo buy → 100% to opening algo (regardless of close)
        - Manual buy + Algo close → 50% Algo / 50% Manual
        - Manual buy + Manual close → 100% Manual

    Args:
        round_trip: A round trip dict from pair_trades().

    Returns:
        dict with: algo_pnl, manual_pnl, attribution_label,
                   open_algo_info, close_algo_info.
    """
    pnl = round_trip["pnl"]
    direction = round_trip["direction"]

    open_source = round_trip["open_trade"]["algo_source"]
    close_source = round_trip["close_trade"]["algo_source"]

    open_info = classify_source(open_source)
    close_info = classify_source(close_source)

    open_is_algo = open_info["is_algo"]
    close_is_algo = close_info["is_algo"]

    if direction == "sell_first":
        if open_is_algo:
            # Algo sell → 100% to opening algo
            algo_pnl = pnl
            manual_pnl = 0.0
            label = open_info["algo_name"]
        elif not open_is_algo and close_is_algo:
            # Manual sell + Algo close → 100% to closing algo
            algo_pnl = pnl
            manual_pnl = 0.0
            label = close_info["algo_name"]
        else:
            # Manual sell + Manual close → 100% Manual
            algo_pnl = 0.0
            manual_pnl = pnl
            label = "Manual"
    else:
        # Buy-first
        if open_is_algo:
            # Algo buy → 100% to opening algo
            algo_pnl = pnl
            manual_pnl = 0.0
            label = open_info["algo_name"]
        elif not open_is_algo and close_is_algo:
            # Manual buy + Algo close → 50/50
            algo_pnl = round(pnl * 0.5, 2)
            manual_pnl = round(pnl * 0.5, 2)
            label = f"50% {close_info['algo_name']} / 50% Manual"
        else:
            # Manual buy + Manual close → 100% Manual
            algo_pnl = 0.0
            manual_pnl = pnl
            label = "Manual"

    # Pick category from whichever side determined the attribution
    if open_is_algo:
        category = open_info["category"]
    elif close_is_algo:
        category = close_info["category"]
    else:
        category = "Other"

    return {
        "algo_pnl": algo_pnl,
        "manual_pnl": manual_pnl,
        "attribution_label": label,
        "category": category,
        "open_algo_info": open_info,
        "close_algo_info": close_info,
    }


