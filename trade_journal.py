# Algo Source → Name & Category Mapping
# ============================================================================

ALGO_CATEGORY_MAP: dict = {
    # Survivor (Breakout)
    "Trending_Market_Code": {"algo_name": "Survivor (NIFTY)", "category": "Breakout"},
    "Trend_Mkt_SENSEX": {"algo_name": "Survivor (SENSEX)", "category": "Breakout"},
    "Trend_Mkt_Stock": {"algo_name": "Survivor (Stock)", "category": "Breakout"},
    # Wave Extractor / Scraper (Mean Reversion)
    "Scraper": {"algo_name": "Wave Extractor (Scraper)", "category": "Mean Reversion"},
    # Bulk Order (Manual gap scripts)
    "Gap-Odr_Manual": {"algo_name": "Manual", "category": "Bulk Order"},
    "Gap-Odr_Auto": {"algo_name": "Manual", "category": "Bulk Order"},
    # Unknown / Default
    "Unknown": {"algo_name": "Unknown", "category": "Bulk Order"},
    # Stop Loss
    "SL_Order": {"algo_name": "Stop Loss", "category": "Manual"},
    # UI-placed tagged orders
    "Expiry Day Trade - Yash": {"algo_name": "Expiry Day Trade - Yash", "category": "Expiry Trade"},
}

# Tags that are considered "algo" (non-manual) for attribution purposes
ALGO_TAGS: set = {
    "Trending_Market_Code",
    "Trend_Mkt_SENSEX",
    "Trend_Mkt_Stock",
    "Scraper",
}

# Market condition options
MARKET_CONDITIONS: list = [
    "Trending Up",
    "Trending Down",
    "Ranging",
    "Volatile",
    "Low Volatility",
    "Expiry Day",
]


def classify_source(algo_source: str) -> dict:
    """Classify an algo_source tag into name, category, and type.

    Args:
        algo_source: The algo_source tag from an executed order.

    Returns:
        dict with keys: algo_name, category, is_algo (bool).
    """
    import re
    # Opaque per-order tags generated by place_duo_order(): "S_<unix>_<rand>" / "B_<unix>_<rand>"
    if re.match(r'^[SB]_\d+_\d+$', algo_source or ""):
        return {"algo_name": "Wave Extractor (Scraper)", "category": "Mean Reversion", "is_algo": True}

    info = ALGO_CATEGORY_MAP.get(algo_source, {
        "algo_name": algo_source or "Unknown",
        "category": "Other",
    })
    return {
        "algo_name": info["algo_name"],
        "category": info["category"],
        "is_algo": algo_source in ALGO_TAGS,
    }


