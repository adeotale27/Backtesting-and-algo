def _get_notes_filepath() -> str:
    """Get filepath for trade notes JSON.

    Returns:
        str: Absolute path to trade_notes.json.
    """
    status_dir = _get_status_dir()
    return os.path.join(status_dir, "trade_notes.json")


def _load_notes() -> dict:
    """Load all trade notes.

    Returns:
        dict: Mapping of note_key → note data.
    """
    filepath = _get_notes_filepath()
    if not os.path.exists(filepath):
        return {}
    try:
        with open(filepath, "r") as f:
            return json.load(f)
    except Exception as e:
        logging.error(f"Error loading trade notes: {e}")
        return {}


def save_trade_note(
    symbol: str,
    trade_date: str,
    note_text: str,
    market_condition: str = "",
    lesson: str = "",
) -> bool:
    """Save a note for a specific trade.

    Args:
        symbol: Trading symbol of the trade.
        trade_date: Date of the trade (YYYY-MM-DD).
        note_text: Free-text note.
        market_condition: Market condition tag.
        lesson: Lesson learned from this trade.

    Returns:
        bool: True if saved successfully.
    """
    try:
        notes = _load_notes()
        key = f"{trade_date}_{symbol}"
        notes[key] = {
            "symbol": symbol,
            "trade_date": trade_date,
            "note": note_text,
            "market_condition": market_condition,
            "lesson": lesson,
            "updated_at": get_ist_now().isoformat(),
        }

        filepath = _get_notes_filepath()
        with open(filepath, "w") as f:
            json.dump(notes, f, indent=2)

        return True
    except Exception as e:
        logging.error(f"Error saving trade note: {e}")
        return False


def get_trade_notes() -> dict:
    """Get all trade notes.

    Returns:
        dict: All notes keyed by date_symbol.
    """
    return _load_notes()


