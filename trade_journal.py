def get_trade_log(start_date: date, end_date: date) -> dict:
    """Get complete trade log with paired round trips and attribution.

    Serves from the SQLite cache (auto-rebuilt when stale). Callers see
    the same return shape as before; the expensive FIFO pairing only runs
    when new order files are detected or on a daily basis.

    Args:
        start_date: Start date (inclusive).
        end_date: End date (inclusive).

    Returns:
        dict with: round_trips (list, newest first), unpaired (list),
        total_orders (int).
    """
    import trade_journal_db as tjdb  # lazy import to avoid circular dependency

    tjdb.ensure_cache_fresh()
    round_trips = tjdb.query_round_trips(str(start_date), str(end_date))
    unpaired = tjdb.query_unpaired(str(start_date), str(end_date))
    return {
        "round_trips": round_trips,
        "unpaired": unpaired,
        "total_orders": len(round_trips) + len(unpaired),
    }


def get_journal_summary(start_date: date, end_date: date) -> dict:
    """Get aggregated P&L summary by attribution source and category.

    Args:
        start_date: Start date (inclusive).
        end_date: End date (inclusive).

    Returns:
        dict with: total_pnl, algo_pnl, manual_pnl, by_algo, by_category,
                   by_date, win_rate, total_trades, insights.
    """
    trade_log = get_trade_log(start_date, end_date)
    round_trips = trade_log["round_trips"]

    total_pnl = 0.0
    algo_pnl = 0.0
    manual_pnl = 0.0
    wins = 0
    losses = 0
    by_algo: dict = {}
    by_category: dict = {}
    by_date: dict = {}

    best_trade: Optional[dict] = None
    worst_trade: Optional[dict] = None

    for rt in round_trips:
        pnl = rt["pnl"]
        attr = rt["attribution"]

        total_pnl += pnl
        algo_pnl += attr["algo_pnl"]
        manual_pnl += attr["manual_pnl"]

        if pnl >= 0:
            wins += 1
        else:
            losses += 1

        # Track best/worst
        if best_trade is None or pnl > best_trade["pnl"]:
            best_trade = rt
        if worst_trade is None or pnl < worst_trade["pnl"]:
            worst_trade = rt

        # Aggregate by algo name
        label = attr["attribution_label"]
        if label not in by_algo:
            by_algo[label] = {
                "pnl": 0.0,
                "trades": 0,
                "wins": 0,
                "losses": 0,
            }
        by_algo[label]["pnl"] += pnl
        by_algo[label]["trades"] += 1
        if pnl >= 0:
            by_algo[label]["wins"] += 1
        else:
            by_algo[label]["losses"] += 1

        # Aggregate by category
        open_cat = attr["open_algo_info"]["category"]
        if open_cat not in by_category:
            by_category[open_cat] = {"pnl": 0.0, "trades": 0}
        by_category[open_cat]["pnl"] += pnl
        by_category[open_cat]["trades"] += 1

        # Aggregate by date (use open trade date)
        trade_date = rt["open_trade"].get("trade_date", "Unknown")
        if trade_date not in by_date:
            by_date[trade_date] = {"pnl": 0.0, "trades": 0}
        by_date[trade_date]["pnl"] += pnl
        by_date[trade_date]["trades"] += 1

    total_trades = wins + losses
    win_rate = round((wins / total_trades) * 100, 1) if total_trades > 0 else 0

    # Round aggregates
    total_pnl = round(total_pnl, 2)
    algo_pnl = round(algo_pnl, 2)
    manual_pnl = round(manual_pnl, 2)
    for key in by_algo:
        by_algo[key]["pnl"] = round(by_algo[key]["pnl"], 2)
    for key in by_category:
        by_category[key]["pnl"] = round(by_category[key]["pnl"], 2)
    for key in by_date:
        by_date[key]["pnl"] = round(by_date[key]["pnl"], 2)

    # Calculate cumulative P&L by date (sorted)
    sorted_dates = sorted(by_date.keys())
    cumulative_pnl: list = []
    running = 0.0
    for d in sorted_dates:
        running += by_date[d]["pnl"]
        cumulative_pnl.append({
            "date": d,
            "daily_pnl": by_date[d]["pnl"],
            "cumulative_pnl": round(running, 2),
            "trades": by_date[d]["trades"],
        })

    return {
        "total_pnl": total_pnl,
        "algo_pnl": algo_pnl,
        "manual_pnl": manual_pnl,
        "total_trades": total_trades,
        "wins": wins,
        "losses": losses,
        "win_rate": win_rate,
        "by_algo": by_algo,
        "by_category": by_category,
        "cumulative_pnl": cumulative_pnl,
        "unpaired_count": len(trade_log["unpaired"]),
        "insights": {
            "best_trade": {
                "symbol": best_trade["symbol"],
                "pnl": best_trade["pnl"],
                "date": best_trade["open_trade"].get("trade_date", ""),
            } if best_trade else None,
            "worst_trade": {
                "symbol": worst_trade["symbol"],
                "pnl": worst_trade["pnl"],
                "date": worst_trade["open_trade"].get("trade_date", ""),
            } if worst_trade else None,
        },
    }


