def inject_carry_forward(
    symbol: str,
    transaction_type: str,
    price: float,
    quantity: int,
    trade_date: date,
    note: str = "",
) -> dict:
    """Inject a synthetic open-leg order to represent a position opened on a prior day.

    Used to fix data gaps where the opening trade was not recorded locally
    (e.g. position opened before local tracking started, or placed manually
    before reconcile was running).

    The synthetic order is tagged algo_source="Carry Forward" and timestamped
    at 09:15:00 IST on trade_date so it sorts before any same-day closes.

    Args:
        symbol: Trading symbol (e.g. 'NIFTY2651223950PE').
        transaction_type: 'BUY' or 'SELL' — the direction of the opening leg.
        price: Average fill price to use for P&L calculation.
        quantity: Number of units.
        trade_date: The date to inject the order into (usually yesterday).
        note: Optional human-readable reason stored in the order.

    Returns:
        dict with keys: success (bool), order (dict), message (str).

    Raises:
        ValueError: If transaction_type is invalid or quantity <= 0.
    """
    if transaction_type not in ("BUY", "SELL"):
        raise ValueError(f"transaction_type must be BUY or SELL, got {transaction_type!r}")
    if quantity <= 0:
        raise ValueError(f"quantity must be positive, got {quantity}")
    if price < 0:
        raise ValueError(f"price must be non-negative, got {price}")

    from common_lib import save_executed_order
    from zoneinfo import ZoneInfo

    IST = ZoneInfo("Asia/Kolkata")
    synthetic_ts = datetime(
        trade_date.year, trade_date.month, trade_date.day,
        9, 15, 0, tzinfo=IST,
    ).isoformat()

    # Build the order dict manually so we can control the timestamp
    status_dir = _get_status_dir()
    date_str = trade_date.strftime("%Y-%m-%d")
    filepath = os.path.join(status_dir, f"executed_orders_{date_str}.json")

    symbol_info = _extract_symbol_info(symbol)
    order: dict = {
        "timestamp": synthetic_ts,
        "symbol": symbol,
        "expiry": symbol_info.get("expiry", ""),
        "option_type": symbol_info.get("option_type", ""),
        "transaction_type": transaction_type,
        "price": float(price),
        "quantity": int(quantity),
        "instrument_token": "",
        "segment": "",
        "algo_source": "Carry Forward",
        "order_id": "",
    }
    if note:
        order["note"] = note

    try:
        if os.path.exists(filepath):
            with open(filepath, "r") as f:
                data = json.load(f)
        else:
            data = {"orders": []}

        data["orders"].append(order)

        with open(filepath, "w") as f:
            json.dump(data, f, indent=2)

        logging.info(
            "inject_carry_forward: injected %s %s x%s @ %.2f into %s",
            transaction_type, symbol, quantity, price, date_str,
        )
        return {"success": True, "order": order, "message": f"Injected into {date_str}"}
    except Exception as exc:
        logging.error("inject_carry_forward: failed: %s", exc)
        return {"success": False, "order": order, "message": str(exc)}


def _extract_symbol_info(symbol: str) -> dict:
    """Extract expiry and option_type from a trading symbol string.

    Args:
        symbol: Trading symbol (e.g. 'NIFTY2651223950PE').

    Returns:
        dict with keys: expiry (str), option_type (str).
    """
    import re
    option_type = "OTHER"
    expiry = "UNKNOWN"
    match = re.search(r"(\d{5,6})(CE|PE|FUT)$", symbol)
    if match:
        expiry = match.group(1)
        option_type = match.group(2)
    return {"expiry": expiry, "option_type": option_type}
